function bindDynamicEvents() {
  document.querySelectorAll("[data-mobile-locale]").forEach((button) => button.addEventListener("click", toggleLocale));
  document.querySelectorAll("[data-mobile-theme]").forEach((button) => button.addEventListener("click", toggleTheme));
  document.querySelectorAll(".mobile-menu a").forEach((link) => link.addEventListener("click", closeMenu));

  document.querySelectorAll("[data-project-toggle]").forEach((button) => {
    button.addEventListener("click", () => {
      const card = button.closest(".project-card");
      const label = button.querySelector("span");
      card.classList.toggle("open");
      label.textContent = card.classList.contains("open") ? label.dataset.openLabel : label.dataset.closedLabel;
    });
  });

  document.querySelectorAll("[data-faq-toggle]").forEach((button) => {
    button.addEventListener("click", () => {
      const item = button.closest(".faq-item");
      document.querySelectorAll(".faq-item").forEach((faq) => {
        if (faq !== item) faq.classList.remove("open");
      });
      item.classList.toggle("open");
    });
  });
}

function closeMenu() {
  document.body.classList.remove("menu-open");
  document.querySelector("[data-mobile-menu]")?.classList.remove("open");
  document.querySelector("[data-menu-toggle]")?.setAttribute("aria-expanded", "false");
  setHtml("[data-menu-icon]", icon("menu", 20));
}

function bindStaticEvents() {
  document.querySelector("[data-locale-toggle]")?.addEventListener("click", toggleLocale);
  document.querySelector("[data-theme-toggle]")?.addEventListener("click", toggleTheme);
  document.querySelector("[data-menu-toggle]")?.addEventListener("click", (event) => {
    const open = !document.querySelector("[data-mobile-menu]").classList.contains("open");
    document.body.classList.toggle("menu-open", open);
    document.querySelector("[data-mobile-menu]").classList.toggle("open", open);
    event.currentTarget.setAttribute("aria-expanded", String(open));
    setHtml("[data-menu-icon]", icon(open ? "x" : "menu", 20));
  });

  document.querySelector("[data-contact-form]")?.addEventListener("submit", (event) => {
    event.preventDefault();
    const current = content[state.locale];
    const data = new FormData(event.currentTarget);
    const name = data.get("name") || "";
    const email = data.get("email") || "";
    const subject = data.get("subject") || current.contact.form.fallbackSubject;
    const message = data.get("message") || "";
    const body = encodeURIComponent(`Name: ${name}\nEmail: ${email}\n\n${message}`);
    window.location.href = `mailto:${profile.email}?subject=${encodeURIComponent(subject)}&body=${body}`;
    document.querySelector("[data-form-status]").textContent = current.contact.form.status;
  });
}

function revealVisible() {
  if (!("IntersectionObserver" in window)) {
    document.querySelectorAll(".reveal").forEach((element) => element.classList.add("visible"));
    return;
  }

  const observer = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add("visible");
        observer.unobserve(entry.target);
      }
    });
  }, { threshold: 0.12 });

  document.querySelectorAll(".reveal").forEach((element) => observer.observe(element));
}

