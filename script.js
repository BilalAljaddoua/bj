function icon(name, size = 20, extraClass = "") {
  return `<svg class="${extraClass}" xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${iconPaths[name] || iconPaths.shield}</svg>`;
}

function getValue(path) {
  return path.split(".").reduce((value, key) => value?.[key], content[state.locale]);
}

function setHtml(selector, html) {
  const element = document.querySelector(selector);
  if (element) element.innerHTML = html;
}

function renderStaticIcons() {
  document.querySelectorAll("[data-icon]").forEach((element) => {
    element.innerHTML = icon(element.dataset.icon, Number(element.dataset.size || 17));
  });
}

function renderI18n() {
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = getValue(element.dataset.i18n);
    if (typeof value === "string") element.textContent = value;
  });

  document.querySelectorAll("[data-placeholder]").forEach((element) => {
    const value = getValue(element.dataset.placeholder);
    if (typeof value === "string") element.setAttribute("placeholder", value);
  });

  const footer = document.querySelector("[data-footer-rights]");
  if (footer) footer.textContent = `© ${new Date().getFullYear()} ${content[state.locale].brand.name}. ${content[state.locale].footer.rights}`;
}

