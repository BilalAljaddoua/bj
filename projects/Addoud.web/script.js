const html = document.documentElement;
const themeToggle = document.querySelector("[data-theme-toggle]");
const langToggle = document.querySelector("[data-lang-toggle]");
const langLabel = document.querySelector("[data-lang-label]");
const menuToggle = document.querySelector("[data-menu-toggle]");
const mobileMenu = document.querySelector("[data-mobile-menu]");
const panelBody = document.querySelector("[data-panel-body]");
const tabButtons = document.querySelectorAll("[data-tab]");
let currentLanguage = "ar";
let activeTabKey = "stock";

function refreshIcons() {
  if (window.lucide) {
    window.lucide.createIcons();
  }
}

function setText(selector, value) {
  const element = document.querySelector(selector);
  if (element && value !== undefined) {
    element.textContent = value;
  }
}

function setTextList(selector, values) {
  document.querySelectorAll(selector).forEach((element, index) => {
    if (values[index] !== undefined) {
      element.textContent = values[index];
    }
  });
}

function setIconLabel(element, value) {
  if (!element || value === undefined) return;
  const icon = element.querySelector("svg, i");
  element.textContent = "";
  if (icon) element.appendChild(icon);
  element.append(` ${value}`);
}

function setCardTexts(selector, cards) {
  document.querySelectorAll(selector).forEach((card, index) => {
    const data = cards[index];
    if (!data) return;
    const [title, description] = data;
    const heading = card.querySelector("h3, strong");
    const paragraph = card.querySelector("p");
    if (heading) heading.textContent = title;
    if (paragraph) paragraph.textContent = description;
  });
}

function setSectionHeader(selector, section) {
  setText(`${selector} .section-eyebrow`, section.eyebrow);
  setText(`${selector} h2`, section.title);
  setText(`${selector} .section-header > p:not(.section-eyebrow)`, section.description);
}

function setTheme(theme) {
  html.dataset.theme = theme;
  localStorage.setItem("addoud-theme", theme);
  const icon = theme === "dark" ? "sun" : "moon";
  themeToggle.innerHTML = `<i data-lucide="${icon}"></i>`;
  themeToggle.setAttribute("aria-label", content[currentLanguage].ui.themeAria);
  refreshIcons();
}

function renderPanel(key) {
  const data = content[currentLanguage].panel[key];
  panelBody.innerHTML = `
    <div class="panel-summary">
      ${data.summary.map(([value, label]) => `<div><strong>${value}</strong><span>${label}</span></div>`).join("")}
    </div>
    <div class="status-table">
      ${data.rows
        .map(
          ([title, note, status, tone]) => `
            <div class="status-row">
              <strong>${title}</strong>
              <span>${note}</span>
              <em class="status-pill ${tone === "teal" ? "" : tone}">${status}</em>
            </div>
          `
        )
        .join("")}
    </div>
  `;
}

function setActiveTab(activeKey) {
  activeTabKey = activeKey;
  tabButtons.forEach((button) => {
    const isActive = button.dataset.tab === activeKey;
    button.classList.toggle("active", isActive);
    button.setAttribute("aria-selected", String(isActive));
  });
  renderPanel(activeKey);
}

function playLanguageMotion() {
  document.body.classList.remove("language-switching");
  void document.body.offsetWidth;
  document.body.classList.add("language-switching");
  window.setTimeout(() => document.body.classList.remove("language-switching"), 420);
}

